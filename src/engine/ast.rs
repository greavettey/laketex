//! # LaTeX Abstract Syntax Tree (AST)
//!
//! Strongly typed representation of a parsed LaTeX document.
//!
//! Defines:
//! - Document metadata (title, author, date, paper size, declared packages)
//! - Structural block elements ([`DocumentBlock`]) including title blocks, abstracts,
//!   numbered sections, paragraphs, equations, tables, and figures
//! - Formatted inline elements ([`InlineSpan`]) including bold, italic, monospace, math,
//!   and citations

use egui::Color32;
use serde::{Deserialize, Serialize};

/// Target physical paper format.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum PaperSize {
    /// International ISO 216 A4 (210 x 297 mm, 595.28 x 841.89 pt)
    A4,
    /// North American Letter (8.5 x 11 in, 612.0 x 792.0 pt)
    Letter,
}

impl Default for PaperSize {
    fn default() -> Self {
        Self::A4
    }
}

impl PaperSize {
    /// Width and height in typographic points (72 pt = 1 inch)
    pub fn dimensions_pt(&self) -> (f32, f32) {
        match self {
            Self::A4 => (595.28, 841.89),      // 210 x 297 mm
            Self::Letter => (612.0, 792.0),     // 8.5 x 11 in
        }
    }
}

/// Metadata extracted from document preamble and title declarations.
#[derive(Debug, Clone)]
pub struct DocumentMetadata {
    /// Document title string (`\title{...}`)
    pub title: Option<String>,
    /// Document author string (`\author{...}`)
    pub author: Option<String>,
    /// Document publication date (`\date{...}`)
    pub date: Option<String>,
    /// Target paper geometry
    pub paper_size: PaperSize,
    /// Base body font size in points (e.g. 10pt, 11pt, 12pt)
    pub base_font_size: f32,
    /// Margin width in typographic points (e.g. 54.0 pt for 0.75in, 72.0 pt for 1in)
    pub margin_pt: f32,
    /// Names of packages imported in preamble
    pub packages: Vec<String>,
}

impl Default for DocumentMetadata {
    fn default() -> Self {
        Self {
            title: None,
            author: None,
            date: None,
            paper_size: PaperSize::A4,
            base_font_size: 11.0,
            margin_pt: 54.0,
            packages: Vec::new(),
        }
    }
}

/// Richly formatted inline text elements within paragraphs or table cells.
#[derive(Debug, Clone)]
pub enum InlineSpan {
    /// Plain body text
    Text(String),
    /// Bold text (`\textbf{...}`)
    Bold(String),
    /// Italic or emphasized text (`\textit{...}`, `\emph{...}`)
    Italic(String),
    /// Monospace code font (`\texttt{...}`)
    Code(String),
    /// Inline math formula (`$...$`)
    Math(String),
    /// Colored text (`\textcolor{color}{...}`)
    Colored(Color32, String),
    /// Hyperlink target (`\href{url}{...}`)
    Url(String),
    /// Cross-reference (`\ref{...}`)
    Ref(String),
    /// Literature citation (`\cite{...}`)
    Cite(String),
}

/// A row in a LaTeX tabular environment.
#[derive(Debug, Clone)]
pub struct TableRow {
    /// Column cells containing formatted inline spans
    pub cells: Vec<Vec<InlineSpan>>,
    /// Whether this row functions as a table header
    pub is_header: bool,
}

/// Structural block-level elements comprising a document.
#[derive(Debug, Clone)]
pub enum DocumentBlock {
    /// Title block generated by `\maketitle`
    TitleBlock {
        /// Source line where `\maketitle` was declared
        line: usize,
    },
    /// Abstract environment (`\begin{abstract} ... \end{abstract}`)
    Abstract {
        /// Content spans
        spans: Vec<InlineSpan>,
        /// Source line where abstract started
        line: usize,
    },
    /// Structural heading (`\section`, `\subsection`, `\subsubsection`, `\paragraph`)
    Section {
        /// Hierarchy level (1 = section, 2 = subsection, 3 = subsubsection, 4 = paragraph)
        level: usize,
        /// Formatted section number string (e.g., "1.2")
        number: String,
        /// Section heading text
        title: String,
        /// Source line number
        line: usize,
    },
    /// Standard body paragraph
    Paragraph {
        /// Paragraph content spans
        spans: Vec<InlineSpan>,
        /// Source line where paragraph began
        line: usize,
    },
    /// Numbered or unnumbered standalone equation
    EquationBlock {
        /// Raw LaTeX mathematical formula string
        formula: String,
        /// Optional equation number
        number: Option<usize>,
        /// Cross-reference label
        label: Option<String>,
        /// Source line number
        line: usize,
    },
    /// Multi-line aligned equation environment (`\begin{align}`)
    AlignBlock {
        /// Individual aligned equation strings
        equations: Vec<String>,
        /// Starting equation number
        start_number: usize,
        /// Source line number
        line: usize,
    },
    /// Itemized or enumerated bullet list
    List {
        /// True for numbered lists (`enumerate`), false for bullets (`itemize`)
        ordered: bool,
        /// List item content spans
        items: Vec<Vec<InlineSpan>>,
        /// Source line number
        line: usize,
    },
    /// Tabular data environment (`table` or `tabular`)
    Table {
        /// Optional table caption
        caption: Option<String>,
        /// Cross-reference label
        label: Option<String>,
        /// Header column labels
        headers: Vec<String>,
        /// Data rows
        rows: Vec<TableRow>,
        /// Whether booktabs rules (\toprule, \midrule, \bottomrule) are applied
        has_booktabs: bool,
        /// Source line number
        line: usize,
    },
    /// Floated graphic or figure environment
    Figure {
        /// Optional figure caption
        caption: Option<String>,
        /// Cross-reference label
        label: Option<String>,
        /// Optional graphic file path from `\includegraphics`
        image_path: Option<String>,
        /// Figure sequence index
        number: usize,
        /// Source line number
        line: usize,
    },
    /// Syntax-highlighted code block (`minted`, `listings`, or `verbatim`)
    CodeBlock {
        /// Programming language identifier (e.g. "python", "rust", "c", "latex")
        language: String,
        /// Raw verbatim code text
        code: String,
        /// Source line number
        line: usize,
    },
    /// Horizontal dividing rule (`\hrule`)
    HorizontalRule {
        /// Source line number
        line: usize,
    },
}

impl DocumentBlock {
    /// Returns the source line number associated with this block for SyncTeX navigation
    pub fn line(&self) -> usize {
        match self {
            Self::TitleBlock { line }
            | Self::Abstract { line, .. }
            | Self::Section { line, .. }
            | Self::Paragraph { line, .. }
            | Self::EquationBlock { line, .. }
            | Self::AlignBlock { line, .. }
            | Self::List { line, .. }
            | Self::Table { line, .. }
            | Self::Figure { line, .. }
            | Self::CodeBlock { line, .. }
            | Self::HorizontalRule { line } => *line,
        }
    }
}

/// Complete Abstract Syntax Tree for a LaTeX document.
#[derive(Debug, Clone, Default)]
pub struct LatexAst {
    /// Document metadata
    pub metadata: DocumentMetadata,
    /// Ordered block elements
    pub blocks: Vec<DocumentBlock>,
}
